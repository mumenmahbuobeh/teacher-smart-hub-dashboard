function handleAddStudentSubmit() {
  const name = document.getElementById('sName').value.trim();
  const cls = document.getElementById('sClass').value;
  if (!name) return;

  const newStudent = {
    id: Date.now(),
    name,
    className: cls,
    grade1: 0,
    grade2: 0,
    grade3: 0,
    status: 'present'
  };

  studentsDb.push(newStudent);
  saveStudentsDb();
  closeModal('addStudentModal');
  document.getElementById('sName').value = '';
  renderStudents();
}

function handleRosterUploadSubmit() {
  const text = document.getElementById('csvText').value;
  const cls = document.getElementById('rClass').value;
  if (!text.trim()) return;

  const names = text.split('\n').map(n => n.trim()).filter(n => n.length > 0);
  names.forEach(name => {
    studentsDb.push({
      id: Date.now() + Math.random(),
      name,
      className: cls,
      grade1: 0,
      grade2: 0,
      grade3: 0,
      status: 'present'
    });
  });

  saveStudentsDb();
  closeModal('rosterUploadModal');
  document.getElementById('csvText').value = '';
  switchStudentClass(cls);
}

function deleteStudent(id) {
  if (confirm(currentLang === 'ar' ? 'هل أنت متأكد من حذف هذا الطالب؟' : 'Are you sure you want to delete this student?')) {
    studentsDb = studentsDb.filter(s => s.id !== id);
    saveStudentsDb();
    renderStudents();
  }
}

