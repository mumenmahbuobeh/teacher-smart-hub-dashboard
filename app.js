function renderGrades() {
  const tbody = document.getElementById('gradesTableBody');
  if(!tbody) return;

  const classStudents = studentsDb.filter(s => s.className === activeClass);
  if(classStudents.length === 0) {
    tbody.innerHTML = `<tr><td colspan="${gradesColumns.length + 2}" style="text-align:center;color:var(--text-3);padding:24px;">لا يوجد طلاب في هذا الصف.</td></tr>`;
    return;
  }

  tbody.innerHTML = classStudents.map(s => {
    if (!s.grades) {
      s.grades = {
        grade1: s.grade1 || 0,
        grade2: s.grade2 || 0,
        grade3: s.grade3 || 0
      };
    }
    
    const inputsHtml = gradesColumns.map(col => {
      const val = s.grades[col.id] !== undefined ? s.grades[col.id] : (s[col.id] || 0);
      const maxVal = col.maxGrade || 100;
      return `<td><input type="number" class="grade-input" value="${val}" min="0" max="${maxVal}" onchange="updateDynamicGrade(${s.id}, '${col.id}', this.value)" /></td>`;
    }).join('');
    
    const avg = calculateStudentAverage(s);
    return `
      <tr>
        <td style="font-weight:700;">${s.name}</td>
        ${inputsHtml}
        <td style="font-family:var(--font-mono);font-weight:bold;color:${avg >= 60 ? 'var(--success)' : 'var(--danger)'}">${avg}%</td>
      </tr>
    `;
  }).join('');
}

function updateDynamicGrade(studentId, colId, value) {
  const student = studentsDb.find(s => s.id === studentId);
  if (student) {
    if (!student.grades) {
      student.grades = {
        grade1: student.grade1 || 0,
        grade2: student.grade2 || 0,
        grade3: student.grade3 || 0
      };
    }
    const col = gradesColumns.find(c => c.id === colId);
    const maxVal = col ? (col.maxGrade || 100) : 100;
    let numericVal = parseInt(value) || 0;
    
    if (numericVal < 0) numericVal = 0;
    if (numericVal > maxVal) {
      alert(currentLang === 'ar' ? `الدرجة المدخلة تتجاوز الدرجة العظمى المحددة للعمود وهي (${maxVal})!` : `The entered grade exceeds the maximum grade allowed for this column (${maxVal})!`);
      numericVal = maxVal;
    }
    
    student.grades[colId] = numericVal;
    saveStudentsDb();
    renderGrades();
    updateGlobalStatistics();
  }
}

