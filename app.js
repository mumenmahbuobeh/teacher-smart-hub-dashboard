// Helper to preview student photo and convert to base64
function previewStudentPhoto(event) {
  const file = event.target.files[0];
  if (!file) return;
  if (file.size > 1024 * 1024) {
    alert(currentLang === 'ar' ? 'حجم الصورة كبير جداً! الحد الأقصى هو 1 ميجابايت.' : 'Photo is too large! Maximum limit is 1MB.');
    event.target.value = '';
    return;
  }
  const reader = new FileReader();
  reader.onload = function(e) {
    document.getElementById('studentPhotoPreview').src = e.target.result;
    document.getElementById('studentPhotoPreview').style.display = 'block';
    document.getElementById('studentPhotoPlaceholder').style.display = 'none';
    document.getElementById('sPhotoBase64').value = e.target.result;
    saveStudentDraft();
  };
  reader.readAsDataURL(file);
}

// Live Validation for individual fields
function validateStudentField(fieldId) {
  const input = document.getElementById(fieldId);
  if (!input) return true;
  const val = input.value.trim();
  const errorSpan = document.getElementById(fieldId + 'Val');
  let isValid = true;
  
  if (fieldId === 'sName') {
    const words = val.split(/\s+/).filter(w => w.length > 0);
    isValid = words.length >= 3;
  } else if (fieldId === 'sCode') {
    isValid = /^\d{8}$/.test(val);
  } else if (fieldId === 'sNationalId') {
    isValid = /^\d{11}$/.test(val);
  } else if (fieldId === 'sDob') {
    isValid = val !== '';
  } else if (fieldId === 'sSection') {
    isValid = val !== '';
  } else if (fieldId === 'sParentName') {
    const words = val.split(/\s+/).filter(w => w.length > 0);
    isValid = words.length >= 2;
  } else if (fieldId === 'sParentPhone') {
    isValid = /^[34567]\d{7}$/.test(val);
  } else if (fieldId === 'sParentEmail') {
    isValid = val === '' || /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(val);
  }
  
  if (errorSpan) {
    if (isValid) {
      errorSpan.style.display = 'none';
      input.classList.remove('form-control-error');
    } else {
      errorSpan.style.display = 'block';
      input.classList.add('form-control-error');
    }
  }
  
  saveStudentDraft();
  return isValid;
}

