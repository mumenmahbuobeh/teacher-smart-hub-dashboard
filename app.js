  const qType = original.type;
  
  let qBank = JSON.parse(localStorage.getItem('questionsBankDb')) || defaultQuestionsBank;
  const currentQuestionsText = activeGeneratedQuiz.questions.map(q => q.question.trim());
  const alternates = qBank.filter(q => q.type === qType && !currentQuestionsText.includes(q.question.trim()));
  
