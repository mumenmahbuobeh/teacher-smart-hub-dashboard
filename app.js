function renderAttendance() {
  const tbody = document.getElementById('attendTableBody');
  if(!tbody) return;

  const classStudents = studentsDb.filter(s => s.className === activeClass);
  if(classStudents.length === 0) {
    tbody.innerHTML = `<tr><td colspan="3" style="text-align:center;color:var(--text-3);padding:24px;">لا يوجد طلاب في هذا الصف.</td></tr>`;
    return;
  }

  tbody.innerHTML = classStudents.map(s => `
    <tr>
      <td style="font-weight:700;">${s.name}</td>
      <td>${s.className}</td>
      <td>
        <div class="attend-btn-group">
          <button class="attend-btn p-btn ${s.status === 'present' ? 'active' : ''}" onclick="setAttend(${s.id}, 'present')">${currentLang === 'ar' ? 'حاضر' : 'Present'}</button>
          <button class="attend-btn a-btn ${s.status === 'absent' ? 'active' : ''}" onclick="setAttend(${s.id}, 'absent')">${currentLang === 'ar' ? 'غياب' : 'Absent'}</button>
          <button class="attend-btn l-btn ${s.status === 'late' ? 'active' : ''}" onclick="setAttend(${s.id}, 'متأخر')">${currentLang === 'ar' ? 'متأخر' : 'Late'}</button>
        </div>
      </td>
    </tr>
  `).join('');
}

function setAttend(id, status) {
  const student = studentsDb.find(s => s.id === id);
  if (student) {
    student.status = status;
    saveStudentsDb();
    renderAttendance();
  }
}

// ---------- Grades Tab Logic ----------
function switchGradesClass(cls) {
  activeClass = cls;
  document.getElementById('gradesClassSelect').value = cls;
  renderGrades();
}

function renderGrades() {
  const tbody = document.getElementById('gradesTableBody');
  if(!tbody) return;

  const classStudents = studentsDb.filter(s => s.className === activeClass);
  if(classStudents.length === 0) {
    tbody.innerHTML = `<tr><td colspan="5" style="text-align:center;color:var(--text-3);padding:24px;">لا يوجد طلاب في هذا الصف.</td></tr>`;
    return;
  }

  tbody.innerHTML = classStudents.map(s => {
    const avg = Math.round(((s.grade1 || 0) + (s.grade2 || 0) + (s.grade3 || 0)) / 3);
    return `
      <tr>
        <td style="font-weight:700;">${s.name}</td>
        <td><input type="number" class="grade-input" value="${s.grade1 || 0}" min="0" max="100" onchange="updateGrade(${s.id}, 'grade1', this.value)" /></td>
        <td><input type="number" class="grade-input" value="${s.grade2 || 0}" min="0" max="100" onchange="updateGrade(${s.id}, 'grade2', this.value)" /></td>
        <td><input type="number" class="grade-input" value="${s.grade3 || 0}" min="0" max="100" onchange="updateGrade(${s.id}, 'grade3', this.value)" /></td>
        <td style="font-family:var(--font-mono);font-weight:bold;color:${avg >= 50 ? 'var(--success)' : 'var(--danger)'}">${avg}%</td>
      </tr>
    `;
  }).join('');
}

function updateGrade(id, field, val) {
  const student = studentsDb.find(s => s.id === id);
  if (student) {
    student[field] = parseInt(val) || 0;
    saveStudentsDb();
    renderGrades();
  }
}

function updateGlobalStatistics() {
  // Update attendance stats in cards
  const total = studentsDb.length;
  if (total > 0) {
    const presents = studentsDb.filter(s => s.status !== 'absent').length;
    const rate = Math.round((presents / total) * 100);
    const avgGrade = Math.round(studentsDb.reduce((acc, s) => acc + ((s.grade1 + s.grade2 + s.grade3) / 3), 0) / total);
    
    // Update live DOM card values (non-animated fallback/quick updates)
    const cards = document.querySelectorAll('.stat-value');
    if (cards[1]) cards[1].textContent = rate + '%';
    if (cards[2]) cards[2].textContent = avgGrade + '%';
  }
}

