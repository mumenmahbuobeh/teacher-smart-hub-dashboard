// ---------- SPA Tab Switching ----------
document.querySelectorAll('.sidebar .nav-item').forEach(item => {
  item.addEventListener('click', () => {
    const tab = item.getAttribute('data-tab');
    if (!tab) return;
    
    document.getElementById('sidebar').classList.remove('open');
    document.querySelectorAll('.sidebar .nav-item').forEach(i => i.classList.remove('active'));
    item.classList.add('active');
    document.querySelectorAll('.tab-content').forEach(c => c.classList.remove('active'));
    
    if (tab === 'dashboard') {
      document.getElementById('dashboardTab').classList.add('active');
    } else if (tab === 'materials') {
      document.getElementById('materialsTab').classList.add('active');
      renderMaterials();
    } else if (tab === 'students') {
      document.getElementById('studentsTab').classList.add('active');
      renderStudents();
    } else if (tab === 'attend') {
      document.getElementById('attendTab').classList.add('active');
      renderAttendance();
    } else if (tab === 'grades') {
      document.getElementById('gradesTab').classList.add('active');
      renderGrades();
    } else if (tab === 'quiz') {
      document.getElementById('quizTab').classList.add('active');
    } else if (tab === 'plan') {
      document.getElementById('planTab').classList.add('active');
    } else {
      alert(currentLang === 'ar' ? 'هذه الميزة ستكون متوفرة قريباً!' : 'This feature will be available soon!');
    }
  });
});

