function moveCardUp(panelId) {
  const panel = document.getElementById(panelId);
  if (!panel) return;
  const parent = panel.parentNode;
  const prev = panel.previousElementSibling;
  if (prev) {
    parent.insertBefore(panel, prev);
  }
}

function moveCardDown(panelId) {
  const panel = document.getElementById(panelId);
  if (!panel) return;
  const parent = panel.parentNode;
  const next = panel.nextElementSibling;
  if (next) {
    parent.insertBefore(next, panel);
  }
}

function openDatePickerModal() {
  const currentDate = new Date().toISOString().split('T')[0];
  const newDate = prompt(
    currentLang === 'ar' ? 'اختر التاريخ (YYYY-MM-DD):' : 'Select date (YYYY-MM-DD):',
    currentDate
  );
  if (newDate) {
    const dateObj = new Date(newDate + 'T00:00:00');
    if (!isNaN(dateObj.getTime())) {
      const badge = document.getElementById('heroDateBadge');
      if (badge) {
        const formatted = dateObj.toLocaleDateString(currentLang === 'ar' ? 'ar-EG' : 'en-US', {
          weekday: 'long', year: 'numeric', month: 'long', day: 'numeric'
        });
        badge.querySelector('span') ? badge.querySelector('span').textContent = formatted : badge.textContent = formatted;
      }
    }
  }
}

