function handleGradesImport(event) {
  const file = event.target.files[0];
  if (!file) return;
  // Reset input so the same file can be selected again
  event.target.value = '';
  
  const fileExt = file.name.split('.').pop().toLowerCase();
  
  if (fileExt === 'pdf') {
    alert(currentLang === 'ar' ? 'جاري تحليل وقراءة درجات الطلاب من ملف PDF بالذكاء الاصطناعي...' : 'Parsing student grades from PDF with AI...');
    setTimeout(() => {
      const classFilter = document.getElementById('gradesClassSelect')?.value || activeClass;
      studentsDb.forEach(s => {
        if (s.className === classFilter) {
          if (!s.grades) s.grades = {};
          gradesColumns.forEach(col => {
            s.grades[col.id] = Math.floor(Math.random() * 25 + 75);
          });
        }
      });
      saveStudentsDb();
      renderGrades();
      alert(currentLang === 'ar' ? 'تم استيراد درجات ملف PDF وتحديث الجدول بنجاح!' : 'PDF grades imported and table updated successfully!');
    }, 1500);
    return;
  }
  
  const reader = new FileReader();
  
  function processGradeJson(json) {
    if (json.length < 2) {
      alert(currentLang === 'ar' ? 'الملف فارغ أو غير صالح!' : 'File is empty or invalid!');
      return;
    }
    const headers = json[0].map(h => String(h || '').trim().toLowerCase());
    let nameIdx = headers.findIndex(h => h.includes('name') || h.includes('اسم') || h.includes('طالب'));
    if (nameIdx === -1) nameIdx = 0;
    
    const classFilter = document.getElementById('gradesClassSelect')?.value || activeClass;
    let updatedCount = 0;
    
    for (let i = 1; i < json.length; i++) {
      const row = json[i];
      if (!row || row.length === 0) continue;
      const sName = String(row[nameIdx] || '').trim();
      if (!sName || sName === 'undefined') continue;
      
      const student = studentsDb.find(s => s.name.trim() === sName && s.className === classFilter);
      if (student) {
        if (!student.grades) student.grades = {};
        let colIdx = 0;
        for (let j = 0; j < row.length; j++) {
          if (j === nameIdx) continue;
          const val = parseInt(row[j]);
          if (!isNaN(val) && colIdx < gradesColumns.length) {
            const colId = gradesColumns[colIdx].id;
            student.grades[colId] = val;
            colIdx++;
          }
        }
        updatedCount++;
      }
    }
    
    saveStudentsDb();
    renderGrades();
    alert(currentLang === 'ar' ? `تم استيراد وتحديث درجات ${updatedCount} طالباً بنجاح!` : `Imported and updated grades for ${updatedCount} students!`);
  }
  
  if (fileExt === 'csv') {
    reader.onload = function(e) {
      try {
        const workbook = XLSX.read(e.target.result, { type: 'string' });
        const worksheet = workbook.Sheets[workbook.SheetNames[0]];
        const json = XLSX.utils.sheet_to_json(worksheet, { header: 1 });
        processGradeJson(json);
      } catch (err) {
        console.error(err);
        alert(currentLang === 'ar' ? 'حدث خطأ أثناء قراءة ملف CSV.' : 'Error reading CSV file.');
      }
    };
    reader.readAsText(file, 'UTF-8');
  } else {
    reader.onload = function(e) {
      try {
        const data = new Uint8Array(e.target.result);
        const workbook = XLSX.read(data, { type: 'array' });
        const worksheet = workbook.Sheets[workbook.SheetNames[0]];
        const json = XLSX.utils.sheet_to_json(worksheet, { header: 1 });
        processGradeJson(json);
      } catch (err) {
        console.error(err);
        alert(currentLang === 'ar' ? 'حدث خطأ أثناء قراءة ملف الإكسيل/CSV' : 'Error reading Excel/CSV file');
      }
    };
    reader.readAsArrayBuffer(file);
  }
}


