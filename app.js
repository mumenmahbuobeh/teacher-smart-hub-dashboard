function downloadMaterial(id) {
  const material = uploadedMaterials.find(m => m.id === id);
  if (!material) return;
  
  let blob;
  let filename = material.title;
  
  if (window.sessionFiles[id]) {
    const file = window.sessionFiles[id];
    blob = file;
    filename = file.name;
  } else {
    const dummyText = `Teacher Smart Hub\n------------------\nTitle: ${material.title}\nClass: ${material.className}\nType: ${material.type}\nDate: ${material.date}\nDescription: ${material.desc}`;
    blob = new Blob([dummyText], { type: 'text/plain;charset=utf-8' });
    const extensions = { pdf: 'pdf', doc: 'docx', image: 'png', video: 'mp4' };
    filename += `.${extensions[material.type] || 'txt'}`;
  }
  
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

function formatBytes(bytes, decimals = 1) {
  if (bytes === 0) return '0 Bytes';
  const k = 1024;
  const dm = decimals < 0 ? 0 : decimals;
  const sizes = ['Bytes', 'KB', 'MB', 'GB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return parseFloat((bytes / Math.pow(k, i)).toFixed(dm)) + ' ' + sizes[i];
}

