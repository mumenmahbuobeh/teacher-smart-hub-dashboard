function renderLeaderboard() {
  const container = document.getElementById('leaderboardList');
  if (!container) return;
  
  // Group stars count by student name
  const studentTotals = {};
  
  // Read all rewards
  starsDb.forEach(r => {
    // If weekly filter, check if reward is within 7 days
    if (currentLeaderboardPeriod === 'weekly') {
      const diffTime = Math.abs(new Date() - new Date(r.date));
      const diffDays = Math.ceil(diffTime / (1000 * 60 * 60 * 24));
      if (diffDays > 7) return;
    }
    // Monthly filter
    if (currentLeaderboardPeriod === 'monthly') {
      const diffTime = Math.abs(new Date() - new Date(r.date));
      const diffDays = Math.ceil(diffTime / (1000 * 60 * 60 * 24));
      if (diffDays > 30) return;
    }
    
    if (!studentTotals[r.studentName]) {
      studentTotals[r.studentName] = {
        name: r.studentName,
        className: r.className,
        stars: 0
      };
    }
    studentTotals[r.studentName].stars += r.stars;
  });
  
  // Convert to sorted array
  const leaderboard = Object.values(studentTotals).sort((a, b) => b.stars - a.stars);
  
  if (leaderboard.length === 0) {
    container.innerHTML = `<div style="text-align:center; padding:24px; color:var(--text-3); font-size:12.5px;">لا توجد نجوم مسجلة لهذه الفترة.</div>`;
    return;
  }
  
  container.innerHTML = leaderboard.map((item, idx) => {
    let medalClass = 'default';
    let medalEmoji = '';
    if (idx === 0) { medalClass = 'gold'; medalEmoji = '🥇'; }
    else if (idx === 1) { medalClass = 'silver'; medalEmoji = '🥈'; }
    else if (idx === 2) { medalClass = 'bronze'; medalEmoji = '🥉'; }
    else { medalEmoji = `#${idx + 1}`; }
    
    return `
      <div style="display:flex; justify-content:space-between; align-items:center; padding:10px 14px; border-bottom:1px solid var(--border-light); background: var(--surface);">
        <div style="display:flex; align-items:center; gap:12px;">
          <div class="star-badge-rank ${medalClass}">${medalEmoji}</div>
          <div>
            <div style="font-weight:700; font-size:13.5px; color:var(--text-1);">${item.name}</div>
            <div style="font-size:11.5px; color:var(--text-3);">${item.className}</div>
          </div>
        </div>
        <div style="display:flex; align-items:center; gap:6px; font-weight:800; color:var(--gold); font-size:14.5px;">
          <span>${item.stars}</span>
          <span>⭐</span>
        </div>
      </div>
    `;
  }).join('');
}

