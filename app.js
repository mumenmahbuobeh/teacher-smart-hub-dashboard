function applyI18n(){
  const dict = i18n[currentLang];
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(dict[key]) el.innerHTML = dict[key];
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el=>{
    const key = el.getAttribute('data-i18n-ph');
    if(dict[key]) el.setAttribute('placeholder', dict[key]);
  });
  
  const matSearch = document.getElementById('materialsSearchInput');
  if(matSearch) matSearch.setAttribute('placeholder', dict.searchMaterialsPh);
  
  renderLists();
  renderMaterials();
  renderStudents();
  renderAttendance();
  renderGrades();
  if (typeof updateCurrentDate === 'function') updateCurrentDate();
  if (typeof fetchLiveWeather === 'function') fetchLiveWeather();
}

