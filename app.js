// ---------- Students Tab Logic ----------
function switchStudentClass(cls) {
  activeClass = cls;
  document.getElementById('currentClassTitle').textContent = `صف ${cls}`;
  document.getElementById('studentsClassSelect').value = cls;
  renderStudents();
}

function renderStudents() {
  const tbody = document.getElementById('studentsTableBody');
  if(!tbody) return;
  
  const classStudents = studentsDb.filter(s => s.className === activeClass);
  if(classStudents.length === 0) {
    tbody.innerHTML = `<tr><td colspan="6" style="text-align:center;color:var(--text-3);padding:24px;">لا يوجد طلاب في هذا الصف حالياً. قم برفع قائمة أو إضافة طلاب.</td></tr>`;
    return;
  }

  tbody.innerHTML = classStudents.map((s, idx) => `
    <tr>
      <td style="font-family:var(--font-mono);">${idx + 1}</td>
      <td style="font-weight:700;">${s.name}</td>
      <td>${s.className}</td>
      <td style="font-family:var(--font-mono);font-weight:700;">${s.grade1 ? s.grade1 : '-'}</td>
      <td>
        <span style="font-weight:700;color:${s.status === 'absent' ? 'var(--danger)' : 'var(--success)'}">
          ${s.status === 'absent' ? (currentLang === 'ar' ? 'غياب' : 'Absent') : (currentLang === 'ar' ? 'حاضر' : 'Present')}
        </span>
      </td>
      <td>
        <div class="material-actions">
          <button class="action-btn btn-delete" onclick="deleteStudent(${s.id})" title="حذف الطالب">
            <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" style="width:14px;height:14px;"><polyline points="3 6 5 6 21 6"/><path d="M19 6v14a2 2 0 0 1-2 2H7a2 2 0 0 1-2-2V6m3 0V4a2 2 0 0 1 2-2h4a2 2 0 0 1 2 2v2"/><line x1="10" y1="11" x2="10" y2="17"/><line x1="14" y1="11" x2="14" y2="17"/></svg>
          </button>
        </div>
      </td>
    </tr>
  `).join('');
}

function handleAddStudentSubmit() {
  const name = document.getElementById('sName').value.trim();
  const cls = document.getElementById('sClass').value;
  if (!name) return;

  const newStudent = {
    id: Date.now(),
    name,
    className: cls,
    grade1: 0,
    grade2: 0,
    grade3: 0,
    status: 'present'
  };

  studentsDb.push(newStudent);
  saveStudentsDb();
  closeModal('addStudentModal');
  document.getElementById('sName').value = '';
  renderStudents();
}

function handleRosterUploadSubmit() {
  const text = document.getElementById('csvText').value;
  const cls = document.getElementById('rClass').value;
  if (!text.trim()) return;

  const names = text.split('\n').map(n => n.trim()).filter(n => n.length > 0);
  names.forEach(name => {
    studentsDb.push({
      id: Date.now() + Math.random(),
      name,
      className: cls,
      grade1: 0,
      grade2: 0,
      grade3: 0,
      status: 'present'
    });
  });

  saveStudentsDb();
  closeModal('rosterUploadModal');
  document.getElementById('csvText').value = '';
  switchStudentClass(cls);
}

function deleteStudent(id) {
  if (confirm(currentLang === 'ar' ? 'هل أنت متأكد من حذف هذا الطالب؟' : 'Are you sure you want to delete this student?')) {
    studentsDb = studentsDb.filter(s => s.id !== id);
    saveStudentsDb();
    renderStudents();
  }
}

