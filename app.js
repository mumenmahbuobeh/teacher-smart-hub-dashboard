function buildHeatmap() {
  const heatmapContainer = document.getElementById('heatmap');
  if (!heatmapContainer) return;
  heatmapContainer.innerHTML = '';
  
  const colors = ['#F1E4B8', '#DEC26A', 'var(--gold)', 'var(--maroon)'];
  // 14 weeks, 5 days each (Sunday to Thursday) = 70 cells
  for (let i = 0; i < 70; i++) {
    const cell = document.createElement('div');
    cell.className = 'hcell';
    const rand = Math.random();
    let color = colors[3];
    if (rand < 0.05) color = colors[0];
    else if (rand < 0.15) color = colors[1];
    else if (rand < 0.4) color = colors[2];
    
    cell.style.background = color;
    
    const week = Math.floor(i / 5) + 1;
    const day = (i % 5) + 1;
    const dayNamesAr = ['الأحد', 'الاثنين', 'الثلاثاء', 'الأربعاء', 'الخميس'];
    const dayNamesEn = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday'];
    const dayName = currentLang === 'ar' ? dayNamesAr[day - 1] : dayNamesEn[day - 1];
    
    const attendanceVal = color === colors[0] ? '80-85%' : (color === colors[1] ? '86-90%' : (color === colors[2] ? '91-95%' : '96-100%'));
    cell.title = currentLang === 'ar' 
      ? `الأسبوع ${week} - ${dayName}: نسبة الحضور ${attendanceVal}`
      : `Week ${week} - ${dayName}: Attendance ${attendanceVal}`;
      
    heatmapContainer.appendChild(cell);
  }
}

function animateCounters() {
  document.querySelectorAll('.stat-value[data-count]').forEach(el => {
    const target = parseFloat(el.getAttribute('data-count'));
    const suffix = el.getAttribute('data-suffix') || '';
    const duration = 1200;
    const startTime = performance.now();
    
    function update(now) {
      const elapsed = now - startTime;
      const progress = Math.min(elapsed / duration, 1);
      const ease = progress * (2 - progress);
      const current = Math.floor(ease * target);
      el.textContent = current + suffix;
      
      if (progress < 1) {
        requestAnimationFrame(update);
      } else {
        el.textContent = target + suffix;
      }
    }
    
    requestAnimationFrame(update);
  });
}

