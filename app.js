function handleWizardFileSelected(event) {
  const file = event.target.files[0];
  if (!file) return;
  
  document.getElementById('wizardSelectedFileName').textContent = file.name;
  document.getElementById('wizardSelectedFileInfo').style.display = 'flex';
  document.getElementById('wizardDropzone').style.display = 'none';
  
  const reader = new FileReader();
  reader.onload = function(e) {
    try {
      if (typeof XLSX === 'undefined') {
        alert(currentLang === 'ar' ? 'مكتبة قراءة الملفات غير محملة، يرجى التأكد من الاتصال بالإنترنت وإعادة المحاولة.' : 'XLSX library is not loaded. Check connection.');
        clearWizardFile();
        return;
      }
      
      const data = new Uint8Array(e.target.result);
      const workbook = XLSX.read(data, { type: 'array', raw: true });
      const firstSheet = workbook.SheetNames[0];
      const worksheet = workbook.Sheets[firstSheet];
      const json = XLSX.utils.sheet_to_json(worksheet, { header: 1, defval: '' });
      
      if (!json || json.length < 2) {
        alert(currentLang === 'ar' ? 'الملف فارغ أو غير صالح!' : 'File is empty or invalid!');
        clearWizardFile();
        return;
      }
      
      wizardParsedData = json.filter(row => row && row.some(cell => cell !== null && cell !== undefined && String(cell).trim() !== ''));
      wizardHeaders = wizardParsedData[0].map(h => String(h || '').trim());
      
      document.getElementById('btnWizardGoToStep2').disabled = false;
    } catch (err) {
      console.error('Error parsing file:', err);
      alert(currentLang === 'ar' ? 'حدث خطأ أثناء قراءة ملف الإكسيل/CSV: ' + err.message : 'Error reading file: ' + err.message);
      clearWizardFile();
    }
  };
  reader.readAsArrayBuffer(file);
}

