function toggleSelectQuestion(qId, checked) {
  if (checked) {
    if (!qbSelectedQuestions.includes(qId)) {
      qbSelectedQuestions.push(qId);
    }
  } else {
    qbSelectedQuestions = qbSelectedQuestions.filter(id => id !== qId);
  }
  document.getElementById('qbSelectedCount').textContent = qbSelectedQuestions.length;
  const compileBtn = document.getElementById('btnCompileExam');
  if (compileBtn) {
    compileBtn.disabled = qbSelectedQuestions.length === 0;
  }
  renderQuestionBank();
}

